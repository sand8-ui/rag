def main() -> None:
    path = Path(__file__).with_name("golden.json")
    payload = json.loads(path.read_text(encoding="utf-8"))
    payload["description"] = (
        "StayWise 检索黄金集。命中条件：sourcePath + sectionTitle 都与 KnowledgeChunk 一致。"
        "题目用客服原话，不照抄标题。k=10 用于 labeled 检索评测；RAGAS 另取 top-3。"
        "groundTruth 供 Faithfulness / AnswerCorrectness 使用。"
    )
    missing = []
    extra = set(GROUND_TRUTH) - {item["id"] for item in payload["cases"]}
    for item in payload["cases"]:
        truth = GROUND_TRUTH.get(item["id"])
        if not truth:
            missing.append(item["id"])
            continue
        item["groundTruth"] = truth
    if missing or extra:
        raise SystemExit(f"id mismatch missing={missing} extra={sorted(extra)}")
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote groundTruth for {len(payload['cases'])} cases -> {path}")


if __name__ == "__main__":
    main()
